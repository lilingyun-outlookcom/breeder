/* ==================== 汇总与查询 ==================== */

export const helpDocs: HelpDoc[] = [commonDoc, loginDoc, ...adminDocs, ...keeperDocs];

const docsByPath: Record<string, HelpDoc> = {};
helpDocs.forEach((d) => (docsByPath[d.path] = d));

/** 按路由路径查找页面手册；动态路由用前缀匹配（如 /keeper/task/123 → /keeper/task/） */
export function findHelpDoc(path: string): HelpDoc | undefined {
  if (docsByPath[path]) return docsByPath[path];
  const prefix = '/' + path.split('/').filter(Boolean).slice(0, -1).join('/') + '/';
  if (docsByPath[prefix]) return docsByPath[prefix];
  return undefined;
}

/** 首页/登录页判断：这些页面点击帮助直接打开完整手册 */
export const HOME_PATHS = ['/admin/dashboard', '/keeper/home', '/login'];

/** 完整手册新窗口地址（基于环境前缀的 hash 路由） */
export function fullManualUrl(): string {
  const base = import.meta.env.BASE_URL || '/';
  return base + '#/help';
}

export function openFullManual(): void {
  window.open(fullManualUrl(), '_blank', 'noopener');
}
